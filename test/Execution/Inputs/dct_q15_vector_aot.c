/* Independent floor-division round-half-even shift. The saturating i40
 * accumulator of the compiled kernel is provably never clamped
 * (|sum| <= 64 * 32767 * 32768 < 2^39), so the exact i64 sum below is the
 * contract value the compiled schedule must reproduce; the declared i16
 * saturation of the boundary is likewise unreachable because the exported
 * value stays in [-16384, 16383]. */
static int16_t roundHalfEvenShift(int64_t value, unsigned shift) {
  int64_t divisor = (int64_t)1 << shift;
  int64_t quotient = value / divisor;
  int64_t remainder = value % divisor;
  if (remainder < 0) {
    --quotient;
    remainder += divisor;
  }
  int64_t half = divisor >> 1;
  if (remainder > half || (remainder == half && (quotient & 1)))
    ++quotient;
  if (quotient > 32767)
    return (int16_t)32767;
  if (quotient < -32768)
    return (int16_t)-32768;
  return (int16_t)quotient;
}

static void referenceDct(const int16_t *input, unsigned extent, const int16_t *coefficients,
                         unsigned shift, int16_t *output) {
  for (unsigned k = 0; k < extent; ++k) {
    int64_t sum = 0;
    for (unsigned n = 0; n < extent; ++n)
      sum += (int64_t)input[n] * coefficients[k * extent + n];
    output[k] = roundHalfEvenShift(sum, shift);
  }
}

static uint32_t nextState(uint32_t state) {
  state ^= state << 13;
  state ^= state >> 17;
  state ^= state << 5;
  return state;
}

static int16_t toSigned16(uint32_t bits) {
  uint32_t low = bits & 0xFFFFu;
  return (int16_t)(low < 32768u ? (int32_t)low : (int32_t)low - 65536);
}

/* Directed corner inputs. The all-maximum and all-minimum rails drive the
 * k = 0 row to its extreme sums — about 2^33 for N = 8, 2^35 for N = 32,
 * and at N = 64 the full worst case the prefix proof ever certifies,
 * 64 * 32768 * 32767 = 2^36 - 2^21 against the i40 rail of 2^39; the
 * alternating rails do the same for the k = N/2 row. */
static void fillDirected(int trial, int16_t *input, unsigned extent) {
  for (unsigned i = 0; i < extent; ++i)
    input[i] = 0;
  switch (trial) {
  case 0:
    break;
  case 1:
    input[0] = INT16_MAX;
    break;
  case 2:
    input[extent - 1] = INT16_MIN;
    break;
  case 3:
    for (unsigned i = 0; i < extent; ++i)
      input[i] = INT16_MAX;
    break;
  case 4:
    for (unsigned i = 0; i < extent; ++i)
      input[i] = INT16_MIN;
    break;
  case 5:
    for (unsigned i = 0; i < extent; ++i)
      input[i] = (i & 1) ? INT16_MIN : INT16_MAX;
    break;
  default:
    for (unsigned i = 0; i < extent; ++i)
      input[i] = (i & 1) ? INT16_MAX : INT16_MIN;
    break;
  }
}

static int check(void (*kernel)(MemRefI16 *, MemRefI16 *), const int16_t *input, unsigned extent,
                 const int16_t *coefficients, unsigned shift, const char *label) {
  MemRefI16 inputRef = {(int16_t *)input, (int16_t *)input, 0, {extent}, {1}};
  MemRefI16 output;
  kernel(&output, &inputRef);

  int16_t expected[64];
  referenceDct(input, extent, coefficients, shift, expected);

  int failed = output.sizes[0] != (int64_t)extent;
  int64_t count = output.sizes[0] < (int64_t)extent ? output.sizes[0] : (int64_t)extent;
  for (int64_t k = 0; k < count; ++k) {
    int16_t actual = output.aligned[output.offset + k * output.strides[0]];
    if (actual != expected[k]) {
      fprintf(stderr, "%s bin %lld: got %d, expected %d\n", label, (long long)k, actual,
              expected[k]);
      failed = 1;
    }
  }
  free(output.allocated);
  return failed;
}

